import { readFileSync } from 'node:fs'

import { environmentBalance, maskIgnorable, SHELL_ESCAPE } from '../latex/scan.js'

/**
 * LaTeX artifact rendering (M11, v3 §9.6).
 *
 * A LaTeX note project is three files, so the generated content is never entangled with the shared
 * template:
 *
 * - `professor-metadata.tex` — the course/provenance metadata, as `\newcommand`s a template can use;
 * - `content.tex` — the generated body (sections, tables, listings, citations);
 * - `main.tex` — a `\documentclass{article}` wrapper that `\input`s the two above. When a template
 *   provides its own `main.tex`, that one is copied instead and `content.tex` is included from it —
 *   the shared template itself is never edited.
 *
 * Everything the model supplies is escaped, so a stray `_` or `&` in a term cannot turn into a
 * compile error — or worse, into an active macro.
 *
 * The one explicit exception is the **`body_tex` route** (sections / examples / derivations): a
 * caller that names `format: "latex"` may hand in raw LaTeX for a body, validated as a fragment by
 * {@link validateTexFragment}, and it is inserted verbatim. That is what makes a document with real
 * formulas, tables, semantic boxes and diagrams generatable in ONE pass instead of "generate
 * escaped text, then rewrite `content.tex`". Nothing else is unescaped — prose fields keep their
 * escaping, and the raw-math `formulas[]` exception of a review is unchanged.
 *
 * @module dsh-professor-spike/src/artifacts/latex
 */

const asArray = (value) => (Array.isArray(value) ? value : [])
const filled = (value) => typeof value === 'string' && value.trim().length > 0

/** Escape the characters that would otherwise be interpreted as LaTeX syntax. */
export function escapeLatex(value) {
  return String(value ?? '')
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([&%$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/</g, '\\textless{}')
    .replace(/>/g, '\\textgreater{}')
    .replace(/--/g, '-{}-')
}

/** Escaped text with newlines turned into paragraph breaks. */
function paragraph(value) {
  return String(value ?? '')
    .split(/\n{2,}/)
    .map((block) => escapeLatex(block.trim()))
    .filter((block) => block.length > 0)
    .join('\n\n')
}

/**
 * Validate a caller-supplied raw LaTeX body (`body_tex`) before anything is written.
 *
 * The check is deliberately bounded: it verifies that the value is a *fragment* a driver can
 * `\input` (no document scaffolding), that its environments balance (comment/verbatim/code aware,
 * so a literal `\begin{...}` inside a listing is not a false positive), and that it requests no
 * shell escape. It does **not** claim to validate TeX syntax — the compile gate and the actual
 * compiler remain the evidence for that.
 *
 * @param fragment - the raw LaTeX body.
 * @returns `{ ok, problems }`.
 */
export function validateTexFragment(fragment) {
  const problems = []
  const text = String(fragment ?? '')
  if (text.trim().length === 0) {
    return { ok: false, problems: ['the LaTeX body is empty'] }
  }
  const masked = maskIgnorable(text)
  if (/\\documentclass\b/.test(masked) || /\\begin\s*\{document\}/.test(masked) || /\\end\s*\{document\}/.test(masked)) {
    problems.push(
      'it is a whole document, not a fragment: \\documentclass / \\begin{document} belong in main.tex — '
      + 'content.tex is \\input by the driver',
    )
  }
  const { unbalanced, unclosed } = environmentBalance(masked)
  if (unbalanced.length > 0) problems.push(`unbalanced environments: ${unbalanced.join(', ')}`)
  if (unclosed.length > 0) problems.push(`environments never closed: ${unclosed.join(', ')}`)
  if (SHELL_ESCAPE.test(masked)) {
    problems.push('the fragment requests shell escape (\\write18 / \\input{|…}), which this plugin never enables by default')
  }
  return { ok: problems.length === 0, problems }
}

function itemize(items) {
  const list = asArray(items).filter(filled).map((item) => `  \\item ${escapeLatex(String(item).trim())}`)
  return list.length === 0 ? '' : ['\\begin{itemize}', ...list, '\\end{itemize}'].join('\n')
}

/** Render the metadata file a template can `\input` and use for its own headers. */
export function renderMetadataTex(input) {
  const course = input.course ?? {}
  const metadata = [
    ['schema', '1'],
    ['kind', input.kind ?? 'note'],
    ['generated_at', input.generated_at ?? ''],
    ['generator', input.generator ?? ''],
    ['course_id', course.course_id ?? ''],
    ['course_code', course.course_code ?? ''],
    ['course_name', course.display_name ?? ''],
    ['course_term', course.term ?? ''],
  ]
  const lines = ['% Generated by dsh-professor-spike — safe to overwrite, do not edit by hand.', '']
  for (const [key, value] of metadata) {
    const macro = `Professor${key.split('_').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('')}`
    lines.push(`\\newcommand{\\${macro}}{${escapeLatex(value)}}`)
  }
  lines.push(`\\newcommand{\\ProfessorTitle}{${escapeLatex(input.title ?? '')}}`)
  return `${lines.join('\n')}\n`
}

/**
 * Render the generated body as a LaTeX fragment.
 *
 * @param input - the artifact input (note or review).
 * @param citations - a value from `buildCitations`, or undefined.
 * @returns the fragment text.
 */
export function renderContentTex(input, citations) {
  const lines = []

  /**
   * The body of a structured entry: an explicit `body_tex` (raw LaTeX, validated by
   * `validateTexFragment`) wins over the escaped prose `body`. Everything else stays escaped.
   */
  const bodyOf = (entry) => (filled(entry?.body_tex)
    ? String(entry.body_tex).replace(/\s+$/, '')
    : paragraph(entry?.body))

  const addSection = (heading, body) => {
    if (!filled(body)) return false
    lines.push(`\\section*{${escapeLatex(heading)}}`, String(body).replace(/\s+$/, ''), '')
    return true
  }

  if (filled(input.summary)) addSection('概述', paragraph(input.summary))
  if (filled(input.scope)) addSection('材料范围', paragraph(input.scope))

  for (const section of asArray(input.sections)) {
    if (!filled(section?.heading)) continue
    addSection(section.heading.trim(), bodyOf(section))
  }

  if (asArray(input.terminology).length > 0) {
    const rows = asArray(input.terminology)
      .filter((entry) => filled(entry?.term))
      .map((entry) => `  ${escapeLatex(entry.term)} & ${escapeLatex(entry.definition ?? '')} \\\\`)
    if (rows.length > 0) {
      addSection('重要术语', [
        '\\begin{tabular}{l p{0.7\\linewidth}}',
        '  \\hline',
        ...rows,
        '  \\hline',
        '\\end{tabular}',
      ].join('\n'))
    }
  }

  for (const example of asArray(input.examples)) {
    const body = bodyOf(example)
    if (!filled(body)) continue
    addSection(filled(example.title) ? example.title : '例题', body)
  }

  addSection('易错点', itemize(input.mistakes))
  addSection('注意事项', itemize(input.warnings))
  addSection('薄弱点', itemize(input.weak_points))
  addSection('重点与难点', itemize(input.important_topics))
  addSection('高频基础', itemize(input.high_frequency))
  addSection('已确认考试范围', itemize(input.confirmed_scope))
  addSection('未确认范围', itemize(input.unconfirmed_scope))
  addSection('反复出错', itemize(input.recurring_mistakes))
  addSection('深挖主题', itemize(input.deep_dives))
  addSection('必备定义', itemize(input.definitions))
  addSection('自测问题', itemize(input.self_check))

  if (asArray(input.formulas).length > 0) {
    addSection('必备公式', ['\\begin{itemize}', ...asArray(input.formulas).filter(filled)
      .map((formula) => `  \\item $\\displaystyle ${String(formula).trim()}$`), '\\end{itemize}'].join('\n'))
  }

  for (const derivation of asArray(input.derivations)) {
    const body = bodyOf(derivation)
    if (!filled(body)) continue
    addSection(filled(derivation.title) ? derivation.title : '推导', body)
  }

  if (asArray(input.practice).length > 0) {
    const body = asArray(input.practice)
      .filter((entry) => filled(entry?.question))
      .map((entry, index) => `\\subsection*{练习 ${index + 1}（${escapeLatex(entry.origin_label ?? entry.origin ?? '未标注')}）}\n\n${paragraph(entry.question)}`)
      .join('\n\n')
    addSection('练习', body)
  }

  if (asArray(input.supplementary).length > 0) {
    addSection('补充说明（模型补充，非教授材料）', [
      itemize(input.supplementary),
      '% The block below is deliberately fenced: it is the model\'s explanation, not professor material.',
      '\\begin{quote}',
      '  以上内容为模型补充，不代表教授讲义的观点或考试范围。',
      '\\end{quote}',
    ].join('\n'))
  }

  if (asArray(input.unresolved).length > 0) {
    addSection('未解决清单', itemize(input.unresolved))
  }

  if (citations !== undefined && asArray(citations.lines).length > 0) {
    const rows = asArray(citations.lines).map((line) => {
      const text = String(line).replace(/^- /, '')
      return `  \\item ${escapeLatex(text)}`
    })
    const extra = [
      ...(citations.hasExternal ? ['\\item 标注 [external] 的条目为外部来源，非课程材料。'] : []),
      ...(citations.hasInference ? ['\\item 标注 [model inference] 的内容为模型推断，不代表教授观点。'] : []),
    ]
    addSection('资料依据', ['\\begin{itemize}', ...rows, ...extra, '\\end{itemize}'].join('\n'))
    if (asArray(citations.conflicts).length > 0) {
      addSection('来源冲突（需人工核对，未静默合并）', itemize(
        citations.conflicts.map((conflict) => `${conflict.key}: ${conflict.refs.length} 条不一致引用`),
      ))
    }
  }

  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}

/**
 * Load the packaged, reference-derived default wrapper when no usable custom template is set.
 * The resource declares Unicode/CJK so the compiler selects XeLaTeX, uses distribution-provided
 * Fandol fonts, and inputs escaped metadata plus the generated body. Explicit user templates keep
 * their own wrapper and compilation requirements. No source-reference identity is inherited.
 */
export function renderMainTex() {
  return readFileSync(new URL('../../resources/latex/default/main.tex', import.meta.url), 'utf8')
}
